"""Phase 3 master orchestrator: run every thrust, persist results + FINDINGS.

Runs single-process (DuckDB is single-writer -- never run while a backfill
writes). Reads the warehouse plus cached external artifacts (Cambium LRMER/SRMER,
CAISO nodal congestion) and produces: the specification-curve figure, all
rank/robustness/triangulation tables, and every FINDINGS.md section.

Caches (regenerated by their modules; committed small CSVs for reproducibility):
  data/cambium_lrmer.csv, data/cambium_srmer.csv, data/nodal_caiso_profile.csv
"""
from __future__ import annotations

import logging
import time

import pandas as pd

from . import multiverse, nodal, thrust1, thrust5
from .causal_mef import triangulate_mef
from .config import Config, load_config
from .docs_util import upsert_section
from .emissions import assemble_hourly, mef_by_ba
from .storage import Warehouse

log = logging.getLogger("gridpulse.phase3")
RECENT_CUT = "2024-07-15"  # comparable full-27-BA window


def _read(wh: Warehouse, table: str, retries: int = 8) -> pd.DataFrame:
    for _ in range(retries):
        try:
            return wh.read(table)
        except Exception as e:  # duckdb lock from a concurrent writer
            log.warning("read %s locked, retry: %s", table, str(e)[:50])
            time.sleep(4)
    return wh.read(table)


def _load_series(cfg: Config, name: str, col: str) -> pd.Series | None:
    p = cfg.data_dir / name
    if not p.exists():
        return None
    df = pd.read_csv(p)
    return df.set_index("ba")[col] if col in df.columns else None


def run_phase3(cfg: Config | None = None) -> dict:
    cfg = cfg or load_config()
    cfg.ensure_dirs()
    wh = Warehouse(cfg)
    fuel_all = _read(wh, "fuel_mix")[["period", "ba", "fueltype", "mwh"]]
    demand_all = _read(wh, "demand")[["period", "ba", "mwh"]]
    interchange = _read(wh, "interchange")
    interchange = interchange[["period", "from_ba", "to_ba", "mwh"]] if not interchange.empty else interchange

    ts = pd.to_datetime(fuel_all["period"])
    fuel = fuel_all[ts >= pd.Timestamp(RECENT_CUT)]
    demand = demand_all[pd.to_datetime(demand_all["period"]) >= pd.Timestamp(RECENT_CUT)]

    out: dict = {}

    # short-run MEF (with CI) computed once, reused across thrusts
    asm = assemble_hourly(fuel, demand)
    mef_df = mef_by_ba(asm, driver="demand", n_boot=500)
    short_run_mef = mef_df.set_index("ba")["mef_kg_per_mwh"]

    # --- Thrust 3: MEF triangulation ---
    tri = triangulate_mef(fuel, demand, sorted(fuel["ba"].unique()))
    tri.to_csv(cfg.data_dir / "mef_triangulation.csv", index=False)
    _write_thrust3(cfg, tri)
    out["triangulation"] = tri

    # --- Thrust 5: probabilistic siting ---
    summ, prob = thrust5.probabilistic_siting(mef_df)
    ties = thrust5.indistinguishable_pairs(prob)
    summ.to_csv(cfg.data_dir / "probabilistic_siting.csv", index=False)
    _write_thrust5(cfg, summ, ties)
    out["prob_siting"] = summ

    # --- Thrust 1: LRMER vs short-run MEF + Holland ---
    lrmer = _load_series(cfg, "cambium_lrmer.csv", "lrmer_co2e")
    srmer = _load_series(cfg, "cambium_srmer.csv", "srmer_co2e")
    if lrmer is not None:
        cmp = thrust1.lrmer_vs_mef(short_run_mef, lrmer)
        cmp.to_csv(cfg.data_dir / "lrmer_vs_mef.csv", index=False)
        _write_thrust1_lrmer(cfg, cmp)
        out["lrmer_vs_mef"] = cmp
    holland = thrust1.holland_test(thrust1.annual_factors(fuel_all, demand_all))
    if not holland.empty:
        holland.to_csv(cfg.data_dir / "holland_test.csv", index=False)
        _write_thrust1_holland(cfg, holland)
        out["holland"] = holland

    # --- Thrust 2: CAISO nodal LME (standalone) ---
    prof = cfg.data_dir / "nodal_caiso_profile.csv"
    if prof.exists() and "CISO" in short_run_mef.index:
        pf = pd.read_csv(prof)
        lme = nodal.nodal_lme_index(pf, float(short_run_mef["CISO"]))
        summary = nodal.intra_ba_summary(pf, lme, float(short_run_mef["CISO"]))
        _write_thrust2(cfg, summary, lme)
        out["nodal_summary"] = summary

    # --- Thrust 6: multiverse capstone (all specs) ---
    extra = {}
    if lrmer is not None:
        extra["LRMER long-run (Cambium)"] = lrmer
    if srmer is not None:
        extra["SRMER short-run (Cambium model)"] = srmer
    specs = multiverse.assemble_specifications(fuel, demand, interchange, extra_specs=extra)
    ranks, rob = multiverse.spec_curve(specs)
    stability = multiverse.top_choice_stability(specs, k=5)
    ranks.to_csv(cfg.data_dir / "multiverse_ranks.csv")
    rob.to_csv(cfg.data_dir / "multiverse_robustness.csv")
    fig = multiverse.chart_spec_curve(ranks, rob, cfg.figs_dir / "spec_curve.png")
    if fig:
        import shutil
        shutil.copy(fig, cfg.repo_root / "docs" / "figs" / "spec_curve.png")
    _write_thrust6(cfg, specs, ranks, rob)
    out.update({"specs": list(specs), "ranks": ranks, "robustness": rob, "stability": stability})

    log.info("phase3 done: %d specs, %d BAs, %d flip", len(specs), len(rob),
             int((rob["verdict"] == "flips").sum()))
    return out


# ---------------------------------------------------------------- FINDINGS writers
def _write_thrust3(cfg: Config, tri: pd.DataFrame) -> None:
    ok = tri.dropna(subset=["mef_siler_evans", "mef_vre_ramp"]).copy()
    ok = ok[ok["n_vre"] >= 100]
    conv = ok[ok["mef_spread_pct"].abs() <= 20]
    lines = [
        "## Thrust 3: MEF validated by independent supply-side instruments", "",
        "The MEF has no published ground truth. We identify it three ways: **Siler-Evans** "
        "(ΔCO2 on Δdemand), a **VRE-ramp instrument** (carbon displaced per MWh of exogenous "
        "wind/solar; Ricks et al.), and **generation-trip** events (forced outages).", "",
        "| BA | Siler-Evans | VRE-ramp | outage | spread % |", "|---|---:|---:|---:|---:|"]
    for _, r in ok.sort_values("mef_spread_pct", key=abs).iterrows():
        og = f"{r['mef_outage']:.0f}" if pd.notna(r["mef_outage"]) else "—"
        lines.append(f"| {r['ba']} | {r['mef_siler_evans']:.0f} | {r['mef_vre_ramp']:.0f} | {og} | {r['mef_spread_pct']:.0f}% |")
    lines += ["", f"**{len(conv)} of {len(ok)} BAs converge within 20%** across independent "
              "methods — real validation where a single fossil unit sets the margin. Estimates "
              "**diverge** in solar/storage/import-heavy BAs (batteries and imports break the "
              "one-margin assumption). Ref: Environ. Res.: Energy 2024, doi:10.1088/2753-3751/ad72f6.", ""]
    upsert_section(cfg.repo_root / "FINDINGS.md",
                   "Thrust 3: MEF validated by independent supply-side instruments", "\n".join(lines))


def _write_thrust5(cfg: Config, summ: pd.DataFrame, ties: pd.DataFrame) -> None:
    top = summ.head(6)
    lines = ["## Thrust 5: probabilistic, uncertainty-aware siting", "",
             "Propagating the MEF bootstrap CIs into the ranking (Monte-Carlo) gives each BA a "
             "*rank distribution*, not a point rank.", "",
             "| BA | MEF | mean rank | P(top-5) | P(rank 1) |", "|---|---:|---:|---:|---:|"]
    for _, r in top.iterrows():
        pcol = [c for c in summ.columns if c.startswith("p_top")][0]
        lines.append(f"| {r['ba']} | {r['mef']:.0f} | {r['rank_mean']:.1f} | {r[pcol]:.2f} | {r['p_rank1']:.2f} |")
    lines += ["", f"**{len(ties)} BA pairs are statistically indistinguishable** (P(greener) in "
              "[0.4, 0.6]) — their 'greener' verdict is a coin flip given MEF uncertainty. Point "
              "rankings hide this; siting should prefer BAs robustly greener across the CI.", ""]
    upsert_section(cfg.repo_root / "FINDINGS.md",
                   "Thrust 5: probabilistic, uncertainty-aware siting", "\n".join(lines))


def _write_thrust1_lrmer(cfg: Config, cmp: pd.DataFrame) -> None:
    movers = cmp.reindex(cmp["rank_shift"].abs().sort_values(ascending=False).index).head(5)
    lines = ["## Thrust 1a: short-run dispatch margin vs long-run build margin (Cambium LRMER)", "",
             "A 15+ year data center induces new capacity, so its true signal is the **long-run** "
             "marginal (NREL Cambium LRMER, kg CO2e/MWh, Mid-case, 2025-2030), not the short-run "
             "dispatch margin (our Siler-Evans MEF). They re-rank BAs.", "",
             "| BA | short-run MEF | long-run LRMER | rank(SR) | rank(LR) | shift |",
             "|---|---:|---:|---:|---:|---:|"]
    for _, r in cmp.iterrows():
        lines.append(f"| {r['ba']} | {r['mef_short_run']:.0f} | {r['lrmer_long_run']:.0f} | "
                     f"{int(r['rank_short_run'])} | {int(r['rank_long_run'])} | {int(r['rank_shift']):+d} |")
    hydro = ", ".join(f"**{r['ba']}** ({int(r['rank_shift']):+d})" for _, r in movers.iterrows())
    lines += ["", f"Biggest re-rankers short-run→long-run: {hydro}. Hydro-rich BAs look greenest "
              "short-run (their extra MWh is existing hydro) but their *long-run* margin is high "
              "(new load induces fossil capacity, not new hydro) — the consequential inversion "
              "(Gagnon/Ricks/Jenkins). Cambium: Gagnon et al., nrel.gov/analysis/cambium.html.", ""]
    upsert_section(cfg.repo_root / "FINDINGS.md",
                   "Thrust 1a: short-run dispatch margin vs long-run build margin (Cambium LRMER)", "\n".join(lines))


def _write_thrust1_holland(cfg: Config, holland: pd.DataFrame) -> None:
    sticky = holland[holland["marginal_stickiness"] < 1.0]
    lines = ["## Thrust 1b: is the marginal factor 'sticky'? (Holland et al. reproduction)", "",
             "Holland et al. (2022, PNAS) found US *marginal* CO2 has not fallen as fast as "
             "*average*. We test it per BA over 2019-present (annual AEF & MEF trends, kg/MWh/yr).", "",
             "| BA | yrs | AEF trend | MEF trend | stickiness (MEF/AEF) |", "|---|---:|---:|---:|---:|"]
    for _, r in holland.sort_values("marginal_stickiness").iterrows():
        lines.append(f"| {r['ba']} | {int(r['n_years'])} | {r['aef_trend_per_yr']:+.1f} | "
                     f"{r['mef_trend_per_yr']:+.1f} | {r['marginal_stickiness']:.2f} |")
    lines += ["", f"In **{len(sticky)} of {len(holland)} BAs the marginal factor is stickier than "
              "the average** (ratio < 1): renewables cut the average while gas still sets the "
              "margin — reproducing Holland et al. on independent live data. Ref: "
              "doi:10.1073/pnas.2116632119.", ""]
    upsert_section(cfg.repo_root / "FINDINGS.md",
                   "Thrust 1b: is the marginal factor 'sticky'? (Holland et al. reproduction)", "\n".join(lines))


