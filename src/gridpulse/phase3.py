def _write_thrust6(cfg: Config, specs: dict, ranks: pd.DataFrame, rob: pd.DataFrame) -> None:
    n_ba, n_flip = len(rob), int((rob["verdict"] == "flips").sum())
    n_green = int((rob["verdict"] == "robust-green").sum())
    n_dirty = int((rob["verdict"] == "robust-dirty").sum())
    flipper = rob.sort_values("rank_range", ascending=False).iloc[0]
    green = ", ".join(rob[rob["verdict"] == "robust-green"].index[:6])
    lines = ["## Thrust 6 (capstone): the siting recommendation is not robust", "",
             f"A per-BA carbon factor is computed under **{len(specs)} specifications** crossing "
             "temporal (short/long-run), accounting (production/consumption), and method "
             "(regression/instrument/Cambium), then BAs are ranked under each (`spec_curve.png`).", "",
             "Specifications: " + "; ".join(f"*{s}*" for s in specs) + ".", "",
             f"**{n_flip} of {n_ba} balancing authorities flip** their siting rank materially "
             f"across specifications. Only **{n_green} are robustly green** ({green}) and "
             f"**{n_dirty} robustly dirty**. The biggest flipper, **{flipper.name}**, ranges rank "
             f"{int(flipper['rank_min'])}→{int(flipper['rank_max'])} on accounting choice alone.", "",
             "**The recommendation is far less robust than single-metric analyses imply.** Only "
             "hydro-dominated regions are unambiguous; elsewhere the accounting choice determines "
             "the answer. Method: specification-curve analysis (Simonsohn et al. 2020, "
             "doi:10.1038/s41562-020-0912-z).", "",
             "| BA | specs | mean rank | min | max | verdict |", "|---|---:|---:|---:|---:|---|"]
    for ba, r in rob.head(18).iterrows():
        lines.append(f"| {ba} | {int(r['n_specs'])} | {r['rank_mean']:.1f} | {int(r['rank_min'])} "
                     f"| {int(r['rank_max'])} | {r['verdict']} |")
    lines.append("")
    upsert_section(cfg.repo_root / "FINDINGS.md",
                   "Thrust 6 (capstone): the siting recommendation is not robust", "\n".join(lines))
