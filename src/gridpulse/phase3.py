"""Phase 3 master orchestrator: run every thrust, persist results + FINDINGS.

Runs single-process (DuckDB is single-writer -- never run while a backfill
writes). Reads the warehouse plus cached external artifacts (Cambium LRMER/SRMER,
CAISO nodal congestion) and produces: the specification-curve figure, all
rank/robustness/triangulation tables, and every FINDINGS.md section.

Caches (regenerated by their modules; committed small CSVs for reproducibility):
  data/cambium_lrmer.csv, data/cambium_srmer.csv, data/nodal_caiso_profile.csv
"""
from __future__ import annotations

import logging
import time

import pandas as pd

from . import multiverse, nodal, robust, state_mef, thrust1, thrust5
from .causal_mef import triangulate_mef
from .config import HAS_STATSMODELS, Config, load_config
from .docs_util import upsert_section
from .emissions import assemble_hourly, mef_by_ba
from .storage import Warehouse

log = logging.getLogger("gridpulse.phase3")
RECENT_CUT = "2024-07-15"  # comparable full-27-BA window


def _read(wh: Warehouse, table: str, retries: int = 8) -> pd.DataFrame:
    for _ in range(retries):
        try:
            return wh.read(table)
        except Exception as e:  # duckdb lock from a concurrent writer
            log.warning("read %s locked, retry: %s", table, str(e)[:50])
            time.sleep(4)
    return wh.read(table)


def _load_series(cfg: Config, name: str, col: str) -> pd.Series | None:
    p = cfg.data_dir / name
    if not p.exists():
        return None
    df = pd.read_csv(p)
    return df.set_index("ba")[col] if col in df.columns else None


def run_phase3(cfg: Config | None = None) -> dict:
    cfg = cfg or load_config()
    cfg.ensure_dirs()
    wh = Warehouse(cfg)
    fuel_all = _read(wh, "fuel_mix")[["period", "ba", "fueltype", "mwh"]]
    demand_all = _read(wh, "demand")[["period", "ba", "mwh"]]
    interchange = _read(wh, "interchange")
    interchange = interchange[["period", "from_ba", "to_ba", "mwh"]] if not interchange.empty else interchange

    ts = pd.to_datetime(fuel_all["period"])
    fuel = fuel_all[ts >= pd.Timestamp(RECENT_CUT)]
    demand = demand_all[pd.to_datetime(demand_all["period"]) >= pd.Timestamp(RECENT_CUT)]

    out: dict = {}

    # short-run MEF (with CI) computed once, reused across thrusts
    asm = assemble_hourly(fuel, demand)
    mef_df = mef_by_ba(asm, driver="demand", n_boot=500)
    short_run_mef = mef_df.set_index("ba")["mef_kg_per_mwh"]

    # --- Thrust 3: MEF triangulation ---
    tri = triangulate_mef(fuel, demand, sorted(fuel["ba"].unique()))
    tri.to_csv(cfg.data_dir / "mef_triangulation.csv", index=False)
    _write_thrust3(cfg, tri)
    out["triangulation"] = tri

    # --- Thrust 7 (Build 2): state-dependent autoregressive MEF (4th estimator) ---
    # Cached like the Cambium CSVs: refit only if the cache is absent and
    # statsmodels is installed (the MS-ARX fit is expensive).
    sp = cfg.data_dir / "state_ar_mef.csv"
    if sp.exists():
        state = pd.read_csv(sp)
    elif HAS_STATSMODELS:
        state = state_mef.state_ar_mef_by_ba(fuel, demand, sorted(fuel["ba"].unique()))
        state.to_csv(sp, index=False)
    else:
        state = pd.DataFrame()
    if not state.empty:
        _write_thrust7(cfg, tri, state)
        out["state_ar"] = state

    # --- Thrust 5: probabilistic siting ---
    summ, prob = thrust5.probabilistic_siting(mef_df)
    ties = thrust5.indistinguishable_pairs(prob)
    summ.to_csv(cfg.data_dir / "probabilistic_siting.csv", index=False)
    _write_thrust5(cfg, summ, ties)
    out["prob_siting"] = summ

    # --- Thrust 1: LRMER vs short-run MEF + Holland ---
    lrmer = _load_series(cfg, "cambium_lrmer.csv", "lrmer_co2e")
    srmer = _load_series(cfg, "cambium_srmer.csv", "srmer_co2e")
    if lrmer is not None:
        cmp = thrust1.lrmer_vs_mef(short_run_mef, lrmer)
        cmp.to_csv(cfg.data_dir / "lrmer_vs_mef.csv", index=False)
        _write_thrust1_lrmer(cfg, cmp)
        out["lrmer_vs_mef"] = cmp
    holland = thrust1.holland_test(thrust1.annual_factors(fuel_all, demand_all))
    if not holland.empty:
        holland.to_csv(cfg.data_dir / "holland_test.csv", index=False)
        _write_thrust1_holland(cfg, holland)
        out["holland"] = holland

    # --- Thrust 2: CAISO nodal LME (standalone) ---
    prof = cfg.data_dir / "nodal_caiso_profile.csv"
    if prof.exists() and "CISO" in short_run_mef.index:
        pf = pd.read_csv(prof)
        lme = nodal.nodal_lme_index(pf, float(short_run_mef["CISO"]))
        summary = nodal.intra_ba_summary(pf, lme, float(short_run_mef["CISO"]))
        _write_thrust2(cfg, summary, lme)
        out["nodal_summary"] = summary

    # --- Thrust 6: multiverse capstone (all specs) ---
    extra = {}
    if lrmer is not None:
        extra["LRMER long-run (Cambium)"] = lrmer
    if srmer is not None:
        extra["SRMER short-run (Cambium model)"] = srmer
    vre_mef = tri.set_index("ba")["mef_vre_ramp"].dropna() if not tri.empty else None
    specs = multiverse.assemble_specifications(fuel, demand, interchange, extra_specs=extra,
                                               vre_mef=vre_mef)
    ranks, rob = multiverse.spec_curve(specs)
    stability = multiverse.top_choice_stability(specs, k=5)
    ranks.to_csv(cfg.data_dir / "multiverse_ranks.csv")
    rob.to_csv(cfg.data_dir / "multiverse_robustness.csv")
    fig = multiverse.chart_spec_curve(ranks, rob, cfg.figs_dir / "spec_curve.png")
    if fig:
        import shutil
        shutil.copy(fig, cfg.repo_root / "docs" / "figs" / "spec_curve.png")
    _write_thrust6(cfg, specs, ranks, rob)
    out.update({"specs": list(specs), "ranks": ranks, "robustness": rob, "stability": stability})

    # --- Build 1: robust siting under accounting-method ambiguity (min-max regret) ---
    # Factor matrix = the 6 multiverse specs plus the Build-2 AR-MEF; the ambiguity
    # set is its marginal methods (drop the average factor AEF). The Thrust-6
    # headline ranks above stay at 6 specs; AR-MEF is reported via Build 2.
    fac_all = pd.DataFrame(specs)
    if not state.empty and "mef_state_ar" in state.columns:
        fac_all["AR-MEF short-run (state-dependent)"] = state.set_index("ba")["mef_state_ar"]
    fac_all.rename_axis("ba").to_csv(cfg.data_dir / "multiverse_factors.csv")
    marginal = fac_all.drop(columns=[robust.AEF_COL], errors="ignore")
    robust.regret_matrix(marginal, "absolute").to_csv(cfg.data_dir / "regret_matrix.csv")
    mmr = robust.min_max_regret(marginal, "absolute")
    mmr.to_csv(cfg.data_dir / "robust_siting.csv")
    unc = None
    try:
        draws = robust.mef_estimation_draws(asm, n_draws=300, method="bootstrap")
        unc = robust.robust_site_under_uncertainty(marginal, draws)
    except Exception as e:  # uncertainty layer is optional; never break the run
        log.warning("robust uncertainty step skipped: %s", str(e)[:60])
    _write_build1(cfg, marginal, mmr, unc)
    out["robust_siting"] = robust.summarize(marginal)

    log.info("phase3 done: %d specs, %d BAs, %d flip", len(specs), len(rob),
             int((rob["verdict"] == "flips").sum()))
    return out


